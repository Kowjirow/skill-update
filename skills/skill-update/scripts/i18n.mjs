let lang = "en";

export function detectLang(...preferred) {
  const candidates = [...preferred, process.env.LC_ALL, process.env.LC_MESSAGES, process.env.LANG, Intl.DateTimeFormat().resolvedOptions().locale];
  for (const c of candidates) {
    const code = String(c ?? "").toLowerCase().slice(0, 2);
    if (MESSAGES[code]) return code;
  }
  return "en";
}

export function setLang(code) {
  lang = MESSAGES[code] ? code : "en";
  return lang;
}

export function t(key, vars = {}) {
  const text = MESSAGES[lang][key] ?? MESSAGES.en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
}
